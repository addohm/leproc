"""Generate Leproc/Data.lua: the spell IDs for every ability and stance name in Leproc/Abilities.lua.

Run it with no arguments: python3 tools/gen_data.py

It downloads WoW: Forever's SpellName table from wago.tools (product wowf) into .scratch/ (reused
for a day), then lists every spell ID whose name matches one of the `names` or a `stance` in
Abilities.lua. Matching by name picks up all ranks. Names with no IDs are reported, so a typo or a
spell Forever doesn't have shows up here rather than as an icon that never lights.
"""
import csv
import datetime
import pathlib
import re
import sys
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
ABILITIES = ROOT / "Leproc" / "Abilities.lua"
DATA = ROOT / "Leproc" / "Data.lua"
CACHE = ROOT / ".scratch" / "SpellName.csv"
URL = "https://wago.tools/db2/SpellName/csv?product=wowf"


def spell_names():
    if not CACHE.exists() or time.time() - CACHE.stat().st_mtime > 86400:
        CACHE.parent.mkdir(exist_ok=True)
        print(f"Downloading {URL}")
        with urllib.request.urlopen(URL, timeout=120) as response:
            CACHE.write_bytes(response.read())
    with CACHE.open(encoding="utf-8", newline="") as f:
        return [(int(row["ID"]), row["Name_lang"]) for row in csv.DictReader(f)]


def wanted_names():
    source = ABILITIES.read_text(encoding="utf-8")
    names = []
    found = re.findall(r"names\s*=\s*\{([^}]*)\}", source) + re.findall(r'stance\s*=\s*("[^"]*")', source)
    for block in found:
        for name in re.findall(r'"((?:[^"\\]|\\.)*)"', block):
            if name not in names:
                names.append(name)
    return names


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = wanted_names()
    ids = {name: [] for name in names}
    for spell_id, name in spell_names():
        if name in ids:
            ids[name].append(spell_id)

    missing = [name for name in names if not ids[name]]
    lines = [
        "-- GENERATED by tools/gen_data.py from wago.tools SpellName (product wowf), "
        + datetime.date.today().isoformat() + ". Don't edit by hand.",
        "-- Every spell ID with each ability or stance name in Abilities.lua.",
        "local _, ns = ...",
        "",
        "ns.SpellIDs = {",
    ]
    for name in names:
        lines.append(f"\t[{lua_string(name)}] = {{ {', '.join(str(i) for i in sorted(ids[name]))} }},")
    lines.append("}")
    DATA.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    print(f"Wrote {DATA.relative_to(ROOT)}: {len(names)} names, {sum(len(v) for v in ids.values())} IDs")
    if missing:
        print("No spell IDs for: " + ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
